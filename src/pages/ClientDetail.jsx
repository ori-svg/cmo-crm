import React, { useState, useEffect } from "react";
import { Client } from "@/api/entities";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import { Badge } from "@/components/ui/badge";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { ArrowRight, Save, Trash2, User, Upload, Download, File, X, Tag, Globe, Calendar as CalendarIcon, Plus } from "lucide-react";
import { useNavigate } from "react-router-dom";
import { createPageUrl } from "@/utils";
import { motion } from "framer-motion";
import { formatDateTime } from "../components/utils/dateUtils";

export default function ClientDetailPage() {
  const navigate = useNavigate();
  const [client, setClient] = useState(null);
  const [isLoading, setIsLoading] = useState(true);
  const [isSaving, setIsSaving] = useState(false);
  const [isUploadingFile, setIsUploadingFile] = useState(false);
  const urlParams = new URLSearchParams(window.location.search);
  const clientId = urlParams.get("id");

  useEffect(() => {
    if (clientId) {
      loadClient();
    } else {
      // Initialize for a new client
      setClient({
        id: null, // Will be generated by the backend
        name: "",
        email: "",
        phone: "",
        status: "פעיל",
        revenue_type: "חד פעמי",
        revenue_amount: 0,
        notes: "",
        payment_date: "", // New field for payment date
      });
      setIsLoading(false); // No loading needed for a new client
    }
  }, [clientId]);

  const loadClient = async () => {
    setIsLoading(true);
    const clients = await Client.list();
    const foundClient = clients.find(c => c.id === clientId);
    if (foundClient) {
      if (!foundClient.files) {
        foundClient.files = [];
      }
      setClient(foundClient);
    }
    setIsLoading(false);
  };

  const handleFileUpload = async (event) => {
    const file = event.target.files[0];
    if (!file) return;

    setIsUploadingFile(true);

    try {
      const { base44 } = await import("@/api/base44Client");
      
      const { file_url } = await base44.integrations.Core.UploadFile({ file });

      const newFile = {
        name: file.name,
        url: file_url,
        size: file.size,
        uploaded_date: new Date().toISOString()
      };

      setClient({
        ...client,
        files: [...(client.files || []), newFile]
      });

      alert(`✅ הקובץ "${file.name}" הועלה בהצלחה`);
    } catch (error) {
      console.error("Error uploading file:", error);
      alert("שגיאה בהעלאת הקובץ");
    } finally {
      setIsUploadingFile(false);
      event.target.value = '';
    }
  };

  const handleRemoveFile = (fileUrl) => {
    if (confirm("האם למחוק את הקובץ?")) {
      setClient({
        ...client,
        files: (client.files || []).filter(f => f.url !== fileUrl)
      });
    }
  };

  const formatFileSize = (bytes) => {
    if (bytes < 1024) return bytes + ' B';
    if (bytes < 1024 * 1024) return (bytes / 1024).toFixed(1) + ' KB';
    return (bytes / (1024 * 1024)).toFixed(1) + ' MB';
  };

  const handleSave = async () => {
    setIsSaving(true);
    
    // אם לא נבחר תאריך תשלום, השתמש בתאריך היום
    const clientToSave = {
      ...client,
      payment_date: client.payment_date || new Date().toISOString().split('T')[0]
    };
    
    if (clientId) {
      // Update existing client
      await Client.update(clientId, clientToSave);
    } else {
      // Create new client
      const clientToCreate = { ...clientToSave };
      delete clientToCreate.id;
      await Client.create(clientToCreate);
    }
    
    setIsSaving(false);
    navigate(createPageUrl("Clients"));
  };

  const handleDelete = async () => {
    if (confirm("האם אתה בטוח שברצונך למחוק לקוח זה?")) {
      await Client.delete(clientId);
      navigate(createPageUrl("Clients"));
    }
  };

  if (isLoading) {
    return (
      <div className="p-8 flex items-center justify-center">
        <div className="text-lg text-gray-500">טוען...</div>
      </div>
    );
  }

  // This block will now only be hit if an ID was provided but no client was found
  if (!client) {
    return (
      <div className="p-8">
        <div className="text-center">
          <p className="text-gray-500">לקוח לא נמצא</p>
          <Button onClick={() => navigate(createPageUrl("Clients"))} className="mt-4">
            חזור ללקוחות
          </Button>
        </div>
      </div>
    );
  }

  return (
    <div className="p-4 md:p-6 lg:p-8 w-full">
      <div className="max-w-4xl mx-auto space-y-6">
        <motion.div
          initial={{ opacity: 0, y: -20 }}
          animate={{ opacity: 1, y: 0 }}
          className="flex items-center gap-4"
        >
          <Button
            variant="ghost"
            onClick={() => navigate(createPageUrl("Clients"))}
            className="gap-2"
          >
            <ArrowRight className="w-4 h-4" />
            חזור
          </Button>
          <div className="flex-1">
            <h1 className="text-2xl md:text-3xl font-bold bg-gradient-to-r from-green-600 to-green-800 bg-clip-text text-transparent">
              {clientId ? "פרטי לקוח" : "יצירת לקוח חדש"}
            </h1>
            <p className="text-gray-500 mt-1 text-sm">
              {clientId ? "ערוך את פרטי הלקוח" : "הוסף פרטים ללקוח חדש"}
            </p>
          </div>
        </motion.div>

        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ delay: 0.1 }}
        >
          <Card className="shadow-lg">
            <CardHeader>
              <CardTitle className="flex items-center gap-2">
                <User className="w-5 h-5 text-green-600" />
                מידע בסיסי
              </CardTitle>
            </CardHeader>
            <CardContent className="space-y-6">
              <div className="space-y-2">
                <Label htmlFor="name">שם מלא</Label>
                <Input
                  id="name"
                  value={client.name || ""}
                  onChange={(e) => setClient({...client, name: e.target.value})}
                />
              </div>

              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                <div className="space-y-2">
                  <Label htmlFor="email">אימייל</Label>
                  <Input
                    id="email"
                    type="email"
                    value={client.email || ""}
                    onChange={(e) => setClient({...client, email: e.target.value})}
                  />
                </div>
                <div className="space-y-2">
                  <Label htmlFor="phone">טלפון</Label>
                  <Input
                    id="phone"
                    value={client.phone || ""}
                    onChange={(e) => setClient({...client, phone: e.target.value})}
                  />
                </div>
              </div>

              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                <div className="space-y-2">
                  <Label htmlFor="status">סטטוס</Label>
                  <Select
                    value={client.status || "פעיל"}
                    onValueChange={(value) => setClient({...client, status: value})}
                  >
                    <SelectTrigger className="brand-select">
                      <SelectValue />
                    </SelectTrigger>
                    <SelectContent>
                      <SelectItem value="פעיל">פעיל</SelectItem>
                      <SelectItem value="לא פעיל">לא פעיל</SelectItem>
                      <SelectItem value="ממתין">ממתין</SelectItem>
                    </SelectContent>
                  </Select>
                </div>
                <div className="space-y-2">
                  <Label htmlFor="revenue_type">אופי ההכנסה</Label>
                  <Select
                    value={client.revenue_type || "חד פעמי"}
                    onValueChange={(value) => setClient({...client, revenue_type: value})}
                  >
                    <SelectTrigger className="brand-select">
                      <SelectValue />
                    </SelectTrigger>
                    <SelectContent>
                      <SelectItem value="חד פעמי">חד פעמי</SelectItem>
                      <SelectItem value="ריטיינר חודשי">ריטיינר חודשי</SelectItem>
                    </SelectContent>
                  </Select>
                </div>
              </div>

              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                <div className="space-y-2">
                  <Label htmlFor="revenue_amount">סכום הכנסה (₪)</Label>
                  <Input
                    id="revenue_amount"
                    type="number"
                    step="0.01"
                    value={client.revenue_amount || ""}
                    onChange={(e) => setClient({...client, revenue_amount: parseFloat(e.target.value) || 0})}
                  />
                  {client.revenue_type === "ריטיינר חודשי" && (
                    <p className="text-xs text-gray-500">
                      סכום חודשי. המערכת תחשב את סך ההכנסות לפי מספר החודשים
                    </p>
                  )}
                </div>

                <div className="space-y-2">
                  <Label htmlFor="payment_date">תאריך תשלום</Label>
                  <Input
                    id="payment_date"
                    type="date"
                    value={client.payment_date || ""}
                    onChange={(e) => setClient({...client, payment_date: e.target.value})}
                  />
                  <p className="text-xs text-gray-500">
                    תאריך התשלום בפועל (למעקב אחר הכנסות)
                  </p>
                </div>
              </div>

              {/* מקור וקמפיין */}
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                <div className="space-y-2">
                  <Label htmlFor="source" className="flex items-center gap-2">
                    <Globe className="w-4 h-4 text-blue-600" />
                    מקור
                  </Label>
                  <Input
                    id="source"
                    value={client.source || ""}
                    onChange={(e) => setClient({...client, source: e.target.value})}
                    placeholder="למשל: פייסבוק, גוגל..."
                  />
                </div>
                <div className="space-y-2">
                  <Label htmlFor="fb_campaign" className="flex items-center gap-2">
                    <CalendarIcon className="w-4 h-4 text-purple-600" />
                    קמפיין
                  </Label>
                  <Input
                    id="fb_campaign"
                    value={client.fb_campaign || ""}
                    onChange={(e) => setClient({...client, fb_campaign: e.target.value})}
                    placeholder="שם הקמפיין"
                  />
                </div>
              </div>

              {/* יום הולדת ומין */}
              {(client.birthday || client.gender) && (
                <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                  {client.birthday && (
                    <div className="space-y-2">
                      <Label htmlFor="birthday">יום הולדת</Label>
                      <Input
                        id="birthday"
                        type="date"
                        value={client.birthday || ""}
                        onChange={(e) => setClient({...client, birthday: e.target.value})}
                      />
                    </div>
                  )}
                  {client.gender && (
                    <div className="space-y-2">
                      <Label htmlFor="gender">מין</Label>
                      <div className="p-3 bg-gray-50 rounded-lg border border-gray-200">
                        <span className="font-medium text-gray-900">{client.gender}</span>
                      </div>
                    </div>
                  )}
                </div>
              )}

              {/* טאגים */}
              {client.tags && client.tags.length > 0 && (
                <div className="space-y-3">
                  <Label className="flex items-center gap-2">
                    <Tag className="w-4 h-4 text-purple-600" />
                    טאגים
                  </Label>
                  <div className="flex flex-wrap gap-2 p-4 bg-gradient-to-r from-purple-50 to-pink-50 rounded-lg border-2 border-purple-200">
                    {client.tags.map((tag, idx) => (
                      <Badge
                        key={idx}
                        className="bg-gradient-to-r from-purple-500 to-pink-500 text-white px-4 py-2"
                      >
                        <Tag className="w-3 h-3 ml-1" />
                        {tag}
                      </Badge>
                    ))}
                  </div>
                </div>
              )}

              {/* הצעות */}
              {client.proposals && client.proposals.length > 0 && (
                <div className="space-y-3">
                  <Label>הצעות שנשלחו</Label>
                  <div className="flex flex-wrap gap-2 p-4 bg-gradient-to-r from-green-50 to-teal-50 rounded-lg border-2 border-green-200">
                    {client.proposals.filter(p => typeof p === 'string').map((proposal, idx) => (
                      <Badge
                        key={idx}
                        className="bg-gradient-to-r from-green-500 to-teal-500 text-white px-4 py-2"
                      >
                        {proposal}
                      </Badge>
                    ))}
                  </div>
                </div>
              )}

              {/* תשובות מטופס */}
              {client.form_responses && (
                <div className="space-y-2">
                  <Label>תשובות מטופס הלידים</Label>
                  <div className="p-4 bg-gray-50 rounded-lg border border-gray-200">
                    <pre className="whitespace-pre-wrap text-sm text-gray-700 font-mono">
                      {client.form_responses}
                    </pre>
                  </div>
                </div>
              )}

              {/* היסטוריית קמפיינים */}
              {client.campaign_history && client.campaign_history.length > 0 && (
                <div className="space-y-3 p-4 bg-gradient-to-r from-purple-50 to-blue-50 rounded-lg border-2 border-purple-200">
                  <div className="flex items-center gap-2 mb-3">
                    <div className="w-8 h-8 bg-purple-600 rounded-full flex items-center justify-center">
                      <CalendarIcon className="w-4 h-4 text-white" />
                    </div>
                    <h3 className="font-bold text-purple-900 text-lg">
                      היסטוריית קמפיינים ({client.campaign_history.length})
                    </h3>
                  </div>
                  
                  <div className="space-y-2">
                    {client.campaign_history.map((entry, idx) => (
                      <Card key={idx} className="bg-white border-purple-200">
                        <CardContent className="p-4">
                          <div className="flex justify-between items-start mb-2">
                            <div>
                              <h4 className="font-semibold text-purple-900 flex items-center gap-2">
                                <Badge className="bg-purple-100 text-purple-800">#{idx + 1}</Badge>
                                {entry.campaign}
                              </h4>
                              <p className="text-xs text-gray-500 mt-1">
                                {formatDateTime(entry.date)}
                              </p>
                            </div>
                            {entry.source && (
                              <Badge variant="outline" className="bg-blue-50">
                                {entry.source}
                              </Badge>
                            )}
                          </div>
                          
                          {entry.form_responses && (
                            <div className="mt-2 p-2 bg-gray-50 rounded text-xs">
                              <strong className="text-gray-700">תשובות מהטופס:</strong>
                              <pre className="mt-1 whitespace-pre-wrap text-gray-600">
                                {entry.form_responses}
                              </pre>
                            </div>
                          )}
                        </CardContent>
                      </Card>
                    ))}
                  </div>
                </div>
              )}

              <div className="space-y-2">
                <Label htmlFor="notes">הערות</Label>
                <Textarea
                  id="notes"
                  value={client.notes || ""}
                  onChange={(e) => setClient({...client, notes: e.target.value})}
                  rows={4}
                  placeholder="הוסף הערות..."
                />
              </div>

              {/* קבצים מצורפים */}
              <div className="space-y-3">
                <Label className="flex items-center gap-2">
                  <File className="w-4 h-4 text-blue-600" />
                  קבצים מצורפים
                </Label>

                <div className="space-y-3 p-4 bg-gradient-to-r from-blue-50 to-cyan-50 rounded-lg border-2 border-blue-200">
                  {/* קבצים קיימים */}
                  {client.files && client.files.length > 0 ? (
                    <div className="space-y-2 mb-4">
                      {client.files.map((file, idx) => (
                        <div
                          key={idx}
                          className="bg-white rounded-lg p-3 border border-blue-200 flex items-center justify-between hover:shadow-md transition-shadow"
                        >
                          <div className="flex items-center gap-3 flex-1 min-w-0">
                            <div className="w-10 h-10 bg-blue-100 rounded-lg flex items-center justify-center flex-shrink-0">
                              <File className="w-5 h-5 text-blue-600" />
                            </div>
                            <div className="flex-1 min-w-0">
                              <p className="font-semibold text-gray-900 truncate">{file.name}</p>
                              <p className="text-xs text-gray-500">
                                {formatFileSize(file.size)} • {new Date(file.uploaded_date).toLocaleDateString('he-IL')}
                              </p>
                            </div>
                          </div>
                          <div className="flex items-center gap-2 flex-shrink-0">
                            <a
                              href={file.url}
                              target="_blank"
                              rel="noopener noreferrer"
                              className="p-2 hover:bg-blue-100 rounded-lg transition-colors"
                            >
                              <Download className="w-4 h-4 text-blue-600" />
                            </a>
                            <button
                              type="button"
                              onClick={() => handleRemoveFile(file.url)}
                              className="p-2 hover:bg-red-100 rounded-lg transition-colors"
                            >
                              <Trash2 className="w-4 h-4 text-red-600" />
                            </button>
                          </div>
                        </div>
                      ))}
                    </div>
                  ) : (
                    <div className="text-center py-4 text-gray-500 text-sm">
                      אין קבצים מצורפים
                    </div>
                  )}

                  {/* כפתור העלאה */}
                  <div className="border-2 border-dashed border-blue-300 rounded-lg p-6 text-center hover:border-blue-500 transition-colors">
                    <Label
                      htmlFor="file-upload"
                      className="cursor-pointer flex flex-col items-center gap-2"
                    >
                      {isUploadingFile ? (
                        <>
                          <div className="w-12 h-12 bg-blue-100 rounded-full flex items-center justify-center animate-pulse">
                            <Upload className="w-6 h-6 text-blue-600" />
                          </div>
                          <span className="text-sm text-blue-600 font-semibold">מעלה קובץ...</span>
                        </>
                      ) : (
                        <>
                          <div className="w-12 h-12 bg-blue-100 rounded-full flex items-center justify-center">
                            <Upload className="w-6 h-6 text-blue-600" />
                          </div>
                          <span className="text-sm text-blue-600 font-semibold hover:text-blue-700">
                            לחץ להעלאת קובץ
                          </span>
                          <span className="text-xs text-gray-500">
                            PDF, Word, Excel, תמונות וכו'
                          </span>
                        </>
                      )}
                    </Label>
                    <Input
                      id="file-upload"
                      type="file"
                      onChange={handleFileUpload}
                      disabled={isUploadingFile}
                      className="hidden"
                    />
                  </div>
                </div>
              </div>

              <div className="flex gap-3 pt-4">
                <Button
                  onClick={handleSave}
                  disabled={isSaving}
                  className="bg-gradient-to-r from-green-600 to-green-700 hover:from-green-700 hover:to-green-800"
                >
                  <Save className="w-4 h-4 ml-2" />
                  {isSaving ? "שומר..." : "שמור שינויים"}
                </Button>
                {clientId && ( // Only show delete button for existing clients
                  <Button
                    variant="destructive"
                    onClick={handleDelete}
                    className="gap-2"
                  >
                    <Trash2 className="w-4 h-4" />
                    מחק לקוח
                  </Button>
                )}
              </div>
            </CardContent>
          </Card>
        </motion.div>
      </div>
    </div>
  );
}